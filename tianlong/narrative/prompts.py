def _section(title: str, lines) -> str:
    lines = [l for l in lines if l]
    return f"【{title}】\n" + "\n".join(f"- {l}" for l in lines) if lines else ""


def _card(c: dict) -> str:
    """一件器物的一行(v8 场景清单)：寻常之物只有名字与方位；器物另有类别、描述与属性；要物在主角手里时另有内容。
    v9：数量(碎银二两、信笺二十张、残卷几张)、钱袋里有多少(在主角手里时)、文书的样子(封着口、撕开的几份之一)、用途(书写、纸)。"""
    out = c["name"] + (f"（{c['spot']}）" if c.get("spot") else "")
    out += "".join(f"｜{x}" for x in (c.get("amount"), c.get("doc"), c.get("kind"), c.get("desc")) if x)
    out += f"｜里头有{c['purse']}" if c.get("purse") else ""
    out += f"｜用途：{'、'.join(c['uses'])}" if c.get("uses") else ""
    out += "".join(f"｜{k}：{v}" for k, v in (c.get("props") or {}).items())
    return out + (f"｜内容：{c['text']}" if c.get("text") else "")


def _flock(q: dict) -> str:
    """一群人的一行(v9)：叫法、站着几人、倒下几人、人人带着什么、是否正围攻你。"""
    fallen = "".join(f"｜{w}{n}人" for w, n in (("倒地", q.get("down")), ("已死", q.get("dead"))) if n)
    return (f"{q['handle']}（{q['name']}，一群算一个整体）｜站着{q['count']}人{fallen}"
            + "".join(f"｜{x}" for x in (q.get("desc"), q.get("kit")) if x) + ("｜正围攻你" if q.get("hostile") else ""))


