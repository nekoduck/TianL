def rechecker(books: dict, disputes: list[dict]) -> tuple[str, str]:
    """双录复核(v7)：词表从正文里看出、账上却没有的几句，交账房逐句裁定。"""
    system = ("你在复核这部武侠文字冒险这一回合的账目。【待复核】里的每一句正文，另一位记账的看出它写了一件变化，账上却没有。逐句裁定：\n"
              "这句写的是已然发生的事——照指令记账(据就照抄那一句里的原文)；不是已然发生的(只是打算、比喻、回忆、台词里的说法、没做成，或另一位看错了)——写进「不记」，说明缘由。"
              "伤了多少、死没死、功力进境、远行由规则结算，不在你记账之列。\n" + SETTLE_OPS +
              '\n输出 JSON：{"changes":[{"据":"正文原句片段","谁":"做这件事的人","ops":[…]}],"不记":[{"据":"那一句","缘由":"一句话"}]}')
    user = (f"【正文】\n{books['text']}\n{_ledger(books)}\n"
            + _section("待复核", [f"「{d['句']}」——另一位看出：{d['看出']}" for d in disputes]))
    return system, user


def recap(synopsis: str, lines: list[str]) -> tuple[str, str]:
    system = ("你是说书人的书记。把【旧梗概】与【新近事】合为一段不超过 200 字的前情梗概：保留人物恩怨、承诺、未了之事与主角处境，"
              "删去细节与形容，按时间先后叙述。近事与梗概里的「你」就是主角，梗概也一律以「你」称他——不要把「你」与主角的名号当成两个人。"
              '输出 JSON：{"synopsis":"…"}')
    return system, f"【旧梗概】{synopsis or '（无）'}\n{_section('新近事', lines)}"


