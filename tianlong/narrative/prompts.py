def _section(title: str, lines) -> str:
    lines = [l for l in lines if l]
    return f"【{title}】\n" + "\n".join(f"- {l}" for l in lines) if lines else ""


def _card(c: dict) -> str:
    """一件器物的一行(v8 场景清单)：寻常之物只有名字与方位；器物另有类别、描述与属性；要物在主角手里时另有内容。
    v9：数量(碎银二两、信笺二十张、残卷几张)、钱袋里有多少(在主角手里时)、文书的样子(封着口、撕开的几份之一)、用途(书写、纸)。"""
    out = c["name"] + (f"（{c['spot']}）" if c.get("spot") else "")
    out += "".join(f"｜{x}" for x in (c.get("amount"), c.get("doc"), c.get("kind"), c.get("desc")) if x)
    out += f"｜里头有{c['purse']}" if c.get("purse") else ""
    out += f"｜用途：{'、'.join(c['uses'])}" if c.get("uses") else ""
    out += "".join(f"｜{k}：{v}" for k, v in (c.get("props") or {}).items())
    return out + (f"｜内容：{c['text']}" if c.get("text") else "")


def _flock(q: dict) -> str:
    """一群人的一行(v9)：叫法、站着几人、倒下几人、人人带着什么、是否正围攻你；v12 另有首领(他也在眼前才写)与眼下之事。"""
    fallen = "".join(f"｜{w}{n}人" for w, n in (("倒地", q.get("down")), ("已死", q.get("dead"))) if n)
    return (f"{q['handle']}（{q['name']}，一群算一个整体）｜站着{q['count']}人{fallen}"
            + "".join(f"｜{x}" for x in (q.get("desc"), q.get("kit")) if x) + ("｜正围攻你" if q.get("hostile") else "") + ("｜正押着你" if q.get("holding") else "")
            + (f"｜首领：{q['leader']}" if q.get("leader") else "") + (f"｜眼下：{q['intent']}" if q.get("intent") else ""))


def _shop(shop: dict | None, staff: bool = False) -> str:
    """此处的铺面(v11)：招牌、开闭、货与价目、能办的事；后台另有当值的伙计、存货与招工。"""
    if not shop:
        return ""
    head = f"【此处铺面】{shop.get('sign') or shop['name']}（{shop.get('type')}" + (f"，{shop['hours']}开闭" if shop.get("hours") else "") + "）"
    lines = [*(f"货·{w}" for w in shop.get("wares") or []), *(f"能办·{s}" for s in shop.get("services") or [])]
    if staff:
        lines = [*(f"伙计·{s}" for s in shop.get("staff") or []), *lines, *(f"招工·{j}" for j in shop.get("jobs") or [])]
        lines += [f"柜上现银：{shop['till']}"] if shop.get("till") else []
    return head + ("\n" + "\n".join(f"- {l}" for l in lines) if lines else "")


